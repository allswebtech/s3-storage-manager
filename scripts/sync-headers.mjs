#!/usr/bin/env node
// Writes vercel.json and public/.htaccess from config/security-headers.js.
//   node scripts/sync-headers.mjs          write both files
//   node scripts/sync-headers.mjs --check  exit 1 when a file is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ASSET_CACHE_CONTROL, HTML_CACHE_CONTROL, SECURITY_HEADERS } from '../config/security-headers.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export function renderVercelJson() {
    const headers = Object.entries(SECURITY_HEADERS).map(([key, value]) => ({ key, value }))
    const config = {
        $schema: 'https://openapi.vercel.sh/vercel.json',
        rewrites: [
            // SPA fallback: every path that is not a real file serves the app.
            { source: '/(.*)', destination: '/index.html' },
        ],
        headers: [
            { source: '/(.*)', headers },
            { source: '/assets/(.*)', headers: [{ key: 'Cache-Control', value: ASSET_CACHE_CONTROL }] },
            { source: '/', headers: [{ key: 'Cache-Control', value: HTML_CACHE_CONTROL }] },
            { source: '/index.html', headers: [{ key: 'Cache-Control', value: HTML_CACHE_CONTROL }] },
        ],
    }
    return `${JSON.stringify(config, null, 4)}\n`
}

// Apache config string: escape backslashes first, then double quotes.
const q = (v) => `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`

export function renderHtaccess() {
    const headerLines = Object.entries(SECURITY_HEADERS)
        .map(([k, v]) => `    Header always set ${k} ${q(v)}`)
        .join('\n')
    return `# Generated by scripts/sync-headers.mjs from config/security-headers.js - do not edit by hand.
# For Apache / LiteSpeed hosts serving the built dist/ folder.

<IfModule mod_rewrite.c>
    RewriteEngine On
    # SPA fallback: requests that are not an existing file or folder load index.html.
    RewriteCond %{REQUEST_FILENAME} !-f
    RewriteCond %{REQUEST_FILENAME} !-d
    RewriteRule ^ index.html [L]
</IfModule>

<IfModule mod_headers.c>
${headerLines}

    # Hashed build assets (assets/name-HASH.ext) never change: cache for a year.
    <FilesMatch "-[A-Za-z0-9_-]{8,}\\.(js|css|svg|png|jpg|woff2?)$">
        Header always set Cache-Control ${q(ASSET_CACHE_CONTROL)}
    </FilesMatch>
    # The HTML entry must be revalidated so new deployments are picked up.
    <FilesMatch "^(index|404)\\.html$">
        Header always set Cache-Control ${q(HTML_CACHE_CONTROL)}
    </FilesMatch>
</IfModule>
`
}

const targets = [
    [join(root, 'vercel.json'), renderVercelJson],
    [join(root, 'public', '.htaccess'), renderHtaccess],
]

if (import.meta.url === `file://${process.argv[1]}`) {
    const check = process.argv.includes('--check')
    let stale = false
    for (const [file, render] of targets) {
        const want = render()
        let have = ''
        try { have = readFileSync(file, 'utf8') } catch { /* missing */ }
        if (have === want) continue
        if (check) {
            console.error(`${file} is out of date: run npm run headers`)
            stale = true
        } else {
            writeFileSync(file, want)
            console.log(`wrote ${file}`)
        }
    }
    if (stale) process.exit(1)
}
